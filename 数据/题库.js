  var W_SENIOR = [12, 15, 17, 18, 19, 19];
  var W_FRESH = [14, 15, 16, 17, 19, 19];   // 大一各项门槛差距小，权重更平缓

  function checklistItems(map, grades) {
    var out = [];
    ABILITY_DIMS.forEach(function (d) {
      map[d.id].forEach(function (text, i) {
        out.push({ id: d.id + (i + 1), dim: d.id, text: text, grades: grades, weight: W_SENIOR[i] });
      });
    });
    return out;
  }

  function checklistItemsFresh(map, grades) {
    var out = [];
    ABILITY_DIMS.forEach(function (d) {
      map[d.id].forEach(function (text, i) {
        out.push({ id: d.id + (i + 1), dim: d.id, text: text, grades: grades, weight: W_FRESH[i] });
      });
    });
    return out;
  }

